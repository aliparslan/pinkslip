function stripMarkdownInline(input: string) {
  return input
    .replace(/\[([^\]]+)\]\(([^)]+)\)/g, "$1 ($2)")
    .replace(/\*\*([^*]+)\*\*/g, "$1")
    .replace(/__([^_]+)__/g, "$1")
    .replace(/\*([^*]+)\*/g, "$1")
    .replace(/_([^_]+)_/g, "$1")
    .replace(/`([^`]+)`/g, "$1")
    .trim();
}

function escapeLatex(input: string) {
  return stripMarkdownInline(input).replace(/[\\&%$#_{}~^]/g, (char) => {
    switch (char) {
      case "\\":
        return String.raw`\textbackslash{}`;
      case "&":
        return String.raw`\&`;
      case "%":
        return String.raw`\%`;
      case "$":
        return String.raw`\$`;
      case "#":
        return String.raw`\#`;
      case "_":
        return String.raw`\_`;
      case "{":
        return String.raw`\{`;
      case "}":
        return String.raw`\}`;
      case "~":
        return String.raw`\textasciitilde{}`;
      case "^":
        return String.raw`\textasciicircum{}`;
      default:
        return char;
    }
  });
}

function headingFromLine(line: string) {
  const markdownHeading = line.match(/^#{1,4}\s+(.+)$/);
  if (markdownHeading) return stripMarkdownInline(markdownHeading[1]).replace(/:$/, "");

  const noColon = stripMarkdownInline(line).replace(/:$/, "");
  if (noColon.length > 2 && noColon.length < 64 && /^[A-Z][A-Z0-9/&., +'-]+$/.test(noColon)) {
    return noColon;
  }

  return null;
}

function parseResumeLines(markdown: string): ResumeLine[] {
  return markdown
    .replace(/\r/g, "")
    .split("\n")
    .map((rawLine) => {
      const line = rawLine.trim();
      if (!line) return { kind: "blank" };

      const heading = headingFromLine(line);
      if (heading) return { kind: "heading", text: heading };

      const bullet = line.match(/^[-*\u2022]\s+(.+)$/);
      if (bullet) return { kind: "bullet", text: bullet[1].trim() };

      return { kind: "text", text: line };
    });
}

function renderTextLine(text: string) {
  const escaped = escapeLatex(text);
  if (text.includes("|") || / -- | - /.test(text)) {
    return String.raw`\textbf{${escaped}}\\[-1pt]`;
  }
  return String.raw`${escaped}\\[-1pt]`;
}

function renderResumeBody(markdown: string, options: RenderResumeBodyOptions = {}) {
  const lines = parseResumeLines(markdown);
  const output: string[] = [];
  let inItems = false;
  let seenHeading = false;
  let headerLines: string[] = [];
  const itemListStart = options.useResumeItemMacros
    ? String.raw`\resumeItemListStart`
    : String.raw`\begin{itemize}`;
  const itemListEnd = options.useResumeItemMacros
    ? String.raw`\resumeItemListEnd`
    : String.raw`\end{itemize}`;

  const closeItems = () => {
    if (!inItems) return;
    output.push(itemListEnd);
    inItems = false;
  };

  const flushHeader = () => {
    if (seenHeading || headerLines.length === 0) return;
    if (options.sourceHeaderTex?.trim()) {
      output.push(options.sourceHeaderTex.trim());
      headerLines = [];
      return;
    }

    const [name, ...contact] = headerLines;
    output.push(String.raw`\begin{center}`);
    output.push(String.raw`  \textbf{\huge \scshape ${escapeLatex(name)}}`);
    if (contact.length > 0) {
      output.push(String.raw`  \\ \vspace{2pt}`);
      output.push(String.raw`  ${escapeLatex(contact.join(" | "))}`);
    }
    output.push(String.raw`\end{center}`);
    output.push(String.raw`\vspace{-12pt}`);
    headerLines = [];
  };

  for (const line of lines) {
    if (line.kind === "blank") {
      closeItems();
      if (!seenHeading) flushHeader();
      continue;
    }

    if (line.kind === "heading") {
      closeItems();
      flushHeader();
      seenHeading = true;
      output.push("");
      output.push(String.raw`\section{${escapeLatex(line.text)}}`);
      continue;
    }

    if (!seenHeading && line.kind === "text") {
      headerLines.push(line.text);
      continue;
    }

    flushHeader();

    if (line.kind === "bullet") {
      if (!inItems) {
        output.push(itemListStart);
        inItems = true;
      }
      output.push(
        options.useResumeItemMacros
          ? String.raw`  \resumeItem{${escapeLatex(line.text)}}`
          : String.raw`  \item ${escapeLatex(line.text)}`
      );
      continue;
    }

    closeItems();
    output.push(renderTextLine(line.text));
  }

  closeItems();
  flushHeader();

  return output.join("\n").trim();
}

function replaceDocumentBody(sourceTex: string, body: string) {
  const begin = sourceTex.indexOf(String.raw`\begin{document}`);
  const end = sourceTex.lastIndexOf(String.raw`\end{document}`);
  if (begin === -1 || end === -1 || end <= begin) return null;

  const beforeDocument = sourceTex.slice(0, begin);
  return `${beforeDocument}${String.raw`\begin{document}`}\n\n${body}\n\n${String.raw`\end{document}`}\n`;
}

function extractSourceHeader(sourceTex: string) {
  const begin = sourceTex.indexOf(String.raw`\begin{document}`);
  const end = sourceTex.lastIndexOf(String.raw`\end{document}`);
  if (begin === -1 || end === -1 || end <= begin) return null;

  const bodyStart = begin + String.raw`\begin{document}`.length;
  const documentBody = sourceTex.slice(bodyStart, end);
  const firstSection = documentBody.search(/\\section\*?\s*\{/);
  if (firstSection === -1) return null;

  const header = documentBody.slice(0, firstSection).trim();
  return header || null;
}

function hasResumeItemMacros(sourceTex: string) {
  return (
    sourceTex.includes(String.raw`\resumeItemListStart`)
    && sourceTex.includes(String.raw`\resumeItem{`)
    && sourceTex.includes(String.raw`\resumeItemListEnd`)
  );
}

export function buildTailoredResumeTex(markdown: string, options: TailoredResumeTexOptions = {}) {
  const sourceTex = options.sourceTex?.trim();
  const body = renderResumeBody(markdown, {
    sourceHeaderTex: sourceTex ? extractSourceHeader(sourceTex) : null,
    useResumeItemMacros: sourceTex ? hasResumeItemMacros(sourceTex) : false,
  });
  const sourceBased = sourceTex ? replaceDocumentBody(sourceTex, body) : null;
  if (sourceBased) {
    return `% Tailored for ${options.companyName ?? "job"} - ${options.jobTitle ?? "role"}\n${sourceBased}`;
  }

  return `% Tailored for ${options.companyName ?? "job"} - ${options.jobTitle ?? "role"}\n${DEFAULT_PREAMBLE}\n\\begin{document}\n\n${body}\n\n\\end{document}\n`;
}

function slugify(input: string) {
  return input
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 80);
}

export function tailoredResumeTexFileName(companyName?: string | null, jobTitle?: string | null) {
  const slug = slugify([companyName, jobTitle, "resume"].filter(Boolean).join(" "));
  return `${slug || "tailored-resume"}.tex`;
}

export function downloadTextFile(fileName: string, text: string, mimeType = "text/plain;charset=utf-8") {
  if (typeof document === "undefined") return;
  const blob = new Blob([text], { type: mimeType });
  const url = URL.createObjectURL(blob);
  try {
    const anchor = document.createElement("a");
    anchor.href = url;
    anchor.download = fileName;
    anchor.rel = "noopener";
    anchor.click();
  } finally {
    window.setTimeout(() => URL.revokeObjectURL(url), 120_000);
  }
}

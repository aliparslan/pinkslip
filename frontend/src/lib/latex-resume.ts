interface TailoredResumeTexOptions {
  companyName?: string | null;
  jobTitle?: string | null;
  sourceTex?: string | null;
}

interface RenderResumeBodyOptions {
  sourceHeaderTex?: string | null;
  useResumeItemMacros?: boolean;
}

type ResumeLine =
  | { kind: "heading"; text: string }
  | { kind: "bullet"; text: string }
  | { kind: "text"; text: string }
  | { kind: "blank" };

interface MarkdownBullet {
  section: string;
  text: string;
}

const STOP_WORDS = new Set([
  "the",
  "and",
  "for",
  "with",
  "from",
  "that",
  "this",
  "into",
  "using",
  "used",
  "via",
  "by",
  "to",
  "of",
  "in",
  "on",
  "a",
  "an",
  "as",
  "at",
  "or",
  "is",
  "are",
  "be",
  "was",
  "were",
]);

const SHORT_TECH_TOKENS = new Set(["ai", "ml", "ui", "ux", "js", "go", "c"]);

